/**
 * Generates site/assets/novra-n-lattice.svg — the N drawn as a triangulated
 * node mesh over a perspective floor.
 *
 * Generated rather than hand-placed for one reason: site/render-assets.mjs
 * compares committed bytes against a fresh render, so the source has to be
 * byte-stable. A seeded PRNG gives a mesh that looks scattered and regenerates
 * identically. Hand-jittered coordinates would look the same and drift.
 *
 * Usage: node site/make-n-lattice.mjs
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "assets", "novra-n-lattice.svg");

// mulberry32 — small, deterministic, and good enough for scatter.
function rng(seed) {
  return () => {
    seed |= 0; seed = (seed + 0x6D2B79F5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = rng(20260901);

const N = [
  [60, 580], [60, 60], [152, 60], [328, 392], [328, 60],
  [420, 60], [420, 580], [328, 580], [152, 248], [152, 580],
];

const inside = (x, y) => {
  let hit = false;
  for (let i = 0, j = N.length - 1; i < N.length; j = i++) {
    const [xi, yi] = N[i], [xj, yj] = N[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
};

// Jittered triangular lattice, clipped to the glyph.
const STEP = 26;
const points = [];
for (let row = 0, y = 52; y <= 590; y += STEP * 0.87, row++) {
  for (let x = 52 + (row % 2 ? STEP / 2 : 0); x <= 430; x += STEP) {
    const px = x + (rand() - 0.5) * 9;
    const py = y + (rand() - 0.5) * 9;
    if (inside(px, py)) points.push([px, py]);
  }
}

// Connect near neighbours. The threshold sits just above the lattice step, so
// each point links to its immediate ring and nothing across the counter.
const LINK = STEP * 1.28;
const edges = [];
for (let i = 0; i < points.length; i++) {
  for (let j = i + 1; j < points.length; j++) {
    const d = Math.hypot(points[i][0] - points[j][0], points[i][1] - points[j][1]);
    if (d < LINK) edges.push([i, j, d / LINK]);
  }
}

const f = (n) => Number(n.toFixed(1));
const edgeSvg = edges.map(([a, b, t]) =>
  `<line x1="${f(points[a][0])}" y1="${f(points[a][1])}" x2="${f(points[b][0])}" y2="${f(points[b][1])}" stroke-opacity="${(0.42 - t * 0.2).toFixed(2)}"/>`
).join("\n    ");

const nodeSvg = points.map(([x, y], i) => {
  const bright = i % 7 === 0;
  return `<circle cx="${f(x)}" cy="${f(y)}" r="${bright ? 3 : 1.9}" fill="${bright ? "#dce6ff" : "#7fb0ff"}" fill-opacity="${bright ? 0.95 : 0.7}"/>`;
}).join("\n    ");

// Perspective floor: verticals fan out from a vanishing point above the horizon.
const VX = 240;
const floor = [];
for (let i = -7; i <= 7; i++) {
  const x = 240 + i * 62;
  floor.push(`<line x1="${f(VX + (x - VX) * 0.34)}" y1="620" x2="${f(VX + (x - VX) * 1.9)}" y2="756" stroke-opacity="0.20"/>`);
}
for (let i = 0; i < 6; i++) {
  const t = i / 5, y = 620 + Math.pow(t, 1.7) * 136;
  floor.push(`<line x1="${f(240 - 40 - t * 300)}" y1="${f(y)}" x2="${f(240 + 40 + t * 300)}" y2="${f(y)}" stroke-opacity="${(0.22 - t * 0.1).toFixed(2)}"/>`);
}

writeFileSync(OUT, `<svg xmlns="http://www.w3.org/2000/svg" width="600" height="760" viewBox="0 0 480 760">
  <!--
    NOVRA N as a node lattice. Generated by site/make-n-lattice.mjs from a
    seeded PRNG so the file is byte-stable across regenerations.

    Decorative, and marked aria-hidden wherever it is placed: the manifesto
    beside it carries the meaning. It is here because the N is the mark, and
    drawing it as a mesh says the thing the page says - structure underneath
    what is immediately visible.
  -->
  <defs>
    <radialGradient id="glow" cx="50%" cy="42%" r="55%">
      <stop offset="0%" stop-color="#2f6bff" stop-opacity="0.30"/>
      <stop offset="60%" stop-color="#7b4dff" stop-opacity="0.09"/>
      <stop offset="100%" stop-color="#05070f" stop-opacity="0"/>
    </radialGradient>
  </defs>
  <rect width="480" height="760" fill="#05070f"/>
  <ellipse cx="240" cy="330" rx="250" ry="290" fill="url(#glow)"/>
  <g stroke="#4d84ff" stroke-width="1">
    ${floor.join("\n    ")}
  </g>
  <g stroke="#4d84ff" stroke-width="1.1">
    ${edgeSvg}
  </g>
  <g>
    ${nodeSvg}
  </g>
</svg>
`);
console.log(`novra-n-lattice.svg — ${points.length} nodes, ${edges.length} edges`);
